# Imports iso\extracted\SCUS_971.33 into a headless Ghidra project under
# recomp\ghidra (git-ignored), auto-analyses it with the Emotion Engine
# extension, and runs PS2Recomp's ExportPS2Functions.java. The function map
# goes to recomp\config\SCUS-97133.functions.csv and the generated TOML is
# rewritten with repo-relative paths into recomp\config\SCUS-97133.toml.
#
# If the Ghidra project already exists it is only re-exported, so names and
# fixes made in the Ghidra GUI are kept. Pass -Reanalyze to start over.

param(
    [string]$GhidraDir = $env:GHIDRA_INSTALL_DIR,
    [switch]$Reanalyze
)

. "$PSScriptRoot\common.ps1"
Set-Location $RepoRoot

$elf = 'iso\extracted\SCUS_971.33'
$projectDir = Join-Path $RepoRoot 'recomp\ghidra'
$projectName = 'SCUS-97133'
$exportDir = Join-Path $projectDir 'export'
$configToml = Join-Path $RepoRoot 'recomp\config\SCUS-97133.toml'
$configCsv = Join-Path $RepoRoot 'recomp\config\SCUS-97133.functions.csv'
$exporterDir = Join-Path $RepoRoot 'external\PS2Recomp\ps2xRecomp\tools\ghidra'

if (-not (Test-Path $elf)) {
    throw "$elf is missing. Run tools\scripts\extract-disc.ps1 first."
}
if (-not $GhidraDir -or -not (Test-Path (Join-Path $GhidraDir 'support\analyzeHeadless.bat'))) {
    throw 'Ghidra not found. Pass -GhidraDir <ghidra_x.y.z_PUBLIC folder> or set GHIDRA_INSTALL_DIR.'
}

# The extension must be built for this exact Ghidra version and installed in
# the user's Extensions folder, which the headless analyzer also loads.
$props = Get-Content (Join-Path $GhidraDir 'Ghidra\application.properties')
$version = ($props | Where-Object { $_ -match '^application\.version=' }) -replace '^application\.version=', ''
$extension = Join-Path $env:APPDATA "ghidra\ghidra_${version}_PUBLIC\Extensions\ghidra-emotionengine-reloaded"
if (-not (Test-Path $extension)) {
    throw "ghidra-emotionengine-reloaded is not installed for Ghidra $version. Download the " +
        "ghidra_${version}_PUBLIC zip from https://github.com/chaoticgd/ghidra-emotionengine-reloaded/releases " +
        "and unzip it into $(Split-Path $extension)."
}

# Release zips ship the .slaspec only; Ghidra compiles it on first use, but
# doing it here keeps the first headless run from depending on that.
$slaspec = Join-Path $extension 'data\languages\r5900.slaspec'
if (-not (Test-Path ([IO.Path]::ChangeExtension($slaspec, '.sla')))) {
    Invoke-Native (Join-Path $GhidraDir 'support\sleigh.bat') @($slaspec)
}

if ($Reanalyze -and (Test-Path $projectDir)) {
    Remove-Item -Recurse -Force (Join-Path $projectDir "$projectName.gpr"), (Join-Path $projectDir "$projectName.rep") -ErrorAction SilentlyContinue
}
New-Item -ItemType Directory -Force -Path $exportDir | Out-Null

$exportToml = Join-Path $exportDir 'SCUS-97133.toml'
$headless = @($projectDir, $projectName)
if (Test-Path (Join-Path $projectDir "$projectName.gpr")) {
    $headless += @('-process', 'SCUS_971.33', '-noanalysis')
} else {
    $headless += @('-import', (Resolve-Path $elf).Path, '-processor', 'r5900:LE:32:default', '-analysisTimeoutPerFile', '3600')
}
$headless += @(
    '-scriptPath', $exporterDir,
    '-postScript', 'ExportPS2Functions.java', $exportToml, $configCsv,
    '-log', (Join-Path $exportDir 'headless.log'),
    '-scriptlog', (Join-Path $exportDir 'script.log')
)
Invoke-Native (Join-Path $GhidraDir 'support\analyzeHeadless.bat') $headless

# The exporter writes absolute paths for this machine; point them back at the
# repo-relative locations recompile.ps1 expects, and add our own settings.
$generated = Get-Content $exportToml | ForEach-Object {
    switch -Regex ($_) {
        '^input = '         { 'input = "iso/extracted/SCUS_971.33"' }
        '^output = '        { 'output = "recomp/generated/"' }
        '^ghidra_output = ' { 'ghidra_output = "recomp/config/SCUS-97133.functions.csv"' }
        '^patch_cache = '   {
            $_
            # Indirect calls return to their own resume entry; only unresolved
            # JR jumps need every instruction of their function as an entry.
            'jalr_indirect_fallback = false'
        }
        default             { $_ }
    }
}
# Jump tables and patches we maintain by hand.
$manualToml = Join-Path $RepoRoot 'recomp\config\SCUS-97133.manual.toml'
if (Test-Path $manualToml) {
    $generated += @('', '# ---- appended from recomp/config/SCUS-97133.manual.toml ----', '') + (Get-Content $manualToml)
}
$header = @(
    '# ps2_recomp configuration for The Getaway, NTSC-U (SCUS-97133).',
    '#',
    '# Generated by tools/scripts/analyze-ghidra.ps1 from PS2Recomp''s Ghidra',
    '# exporter. Paths are relative to the repository root. Every address',
    '# belongs to this exact ELF (boot ELF CRC32 82DA90E7) and is not portable',
    '# to the PAL releases. Hand edits here are lost on the next export: put',
    '# them in SCUS-97133.manual.toml (appended below) or the Ghidra project.',
    '#'
)
[IO.File]::WriteAllLines($configToml, [string[]]($header + $generated))  # UTF-8, no BOM
Write-Host "Wrote $configToml and $configCsv"
